"""Benchmarks that answer questions, in a scratch database that is dropped afterwards.

1. How do the pipeline steps scale with the number of players?
2. Where does the time of one analysis go: reading the mart, the statistics, the bootstrap?
"""

from __future__ import annotations

import time
from datetime import UTC, datetime

from . import ch, marts
from .analyze import _columns, analyze, estimate_metric, load_arms
from .config import load_catalog
from .migrate import migrate
from .simulate import load, load_scenario, simulate

SCRATCH = "gamma_bench"


def _timed(fn):
    t = time.perf_counter()
    out = fn()
    return time.perf_counter() - t, out


def run(sizes: list[int]) -> str:
    cat = load_catalog()
    admin = ch.connect()
    admin.command(f"DROP DATABASE IF EXISTS {SCRATCH}")
    admin.command(f"CREATE DATABASE {SCRATCH}")
    rows = []
    breakdown = ""
    try:
        client = ch.connect(SCRATCH)
        migrate(client)
        for n in sizes:
            scenario = load_scenario()
            scenario.players = n
            t_gen, data = _timed(lambda scenario=scenario: simulate(scenario, cat))
            t_load, _ = _timed(lambda data=data: load(client, data))
            t_mart, _ = _timed(lambda: [marts.build(client, e) for e in cat.experiments.values()])
            exp = cat.experiments["welcome_bonus"]
            t_an, _ = _timed(lambda exp=exp: analyze(client, exp, cat.metrics, bootstrap=False))
            t_an_b, _ = _timed(lambda exp=exp: analyze(client, exp, cat.metrics, bootstrap=True))
            rows.append((n, data.sizes["bets"], t_gen, t_load, t_mart, t_an, t_an_b))
            if n == sizes[-1]:
                used = [cat.metrics[m] for m in exp.metric_names]
                t_read, (arms, _) = _timed(lambda: load_arms(client, exp.key, _columns(used)))
                t_est, _ = _timed(
                    lambda: [
                        estimate_metric(m, arms["control"], arms["treatment"], 0.05) for m in used
                    ]
                )
                t_build, _ = _timed(lambda: marts.build(client, exp))
                breakdown = (
                    f"One analysis of `welcome_bonus` at {n:,} players ({t_an_b:.1f} s with the "
                    f"bootstrap, {t_an:.1f} s without): rebuilding the mart {t_build:.1f} s, reading "
                    f"it into numpy {t_read:.1f} s, all estimators (z, Welch, delta, CUPED) {t_est:.2f} s, "
                    f"bootstrap of the money metrics {t_an_b - t_an:.1f} s. The statistics are cheap; "
                    "the time is in ClickHouse and in the resampling."
                )
    finally:
        admin.command(f"DROP DATABASE IF EXISTS {SCRATCH}")
    out = [
        "# Benchmarks",
        "",
        f"Generated by `gamma bench` on {datetime.now(UTC):%Y-%m-%d}, ClickHouse 24.8 in Docker on the"
        " same machine as the Python process. Wall-clock seconds of a single run in a scratch database"
        " on shared cores: read ratios and shapes, not absolute numbers.",
        "",
        "## Scaling with the number of players",
        "",
        "Three experiments run on the same players. *Marts* builds all three; *analysis* is one"
        " experiment (`welcome_bonus`) including a mart rebuild, without and with the bootstrap of the"
        " money metrics.",
        "",
        "| Players | Bets | Generate | Load | Marts (3 experiments) | Analysis | Analysis + bootstrap |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for n, bets, g, ld, m, a, ab in rows:
        out.append(
            f"| {n:,} | {bets / 1e6:.2f}M | {g:.1f} s | {ld:.1f} s | {m:.1f} s | {a:.1f} s | {ab:.1f} s |"
        )
    first, last = rows[0], rows[-1]
    out += [
        "",
        f"Going from {first[0]:,} to {last[0]:,} players ({last[0] / first[0]:.0f}x) the marts took"
        f" {last[4] / first[4]:.1f}x as long and the analysis {last[5] / first[5]:.1f}x.",
        "",
        "## Where the time of an analysis goes",
        "",
        breakdown,
        "",
    ]
    return "\n".join(out)

"""Runs the method checks on the player-level data of an experiment known to have no effect and
renders them as a Markdown document."""

from __future__ import annotations

import time
from datetime import UTC, datetime

import numpy as np
from clickhouse_connect.driver.client import Client

from ..analyze import _columns, load_arms
from ..config import Catalog
from . import sequential, validate

NULL_EXPERIMENT = "lobby_layout"
FPR_METRICS = ["deposit_conversion", "deposit_per_player", "bets_per_player", "margin"]
POWER_CASES = [
    ("deposit_conversion", 0.05),
    ("deposit_per_player", 0.10),
    ("bets_per_player", 0.03),
]


def run(client: Client, catalog: Catalog, trials: int = 2000, n: int = 10_000) -> str:
    started = time.time()
    metrics = catalog.metrics
    needed = {*FPR_METRICS, *(m for m, _ in POWER_CASES)}
    arms, _ = load_arms(client, NULL_EXPERIMENT, _columns([metrics[m] for m in needed]))
    pop = {k: np.concatenate([arms["control"][k], arms["treatment"][k]]) for k in arms["control"]}
    players = len(pop["converted"])

    fpr = validate.false_positive_rates(pop, [metrics[m] for m in FPR_METRICS], n, trials)
    power = [validate.power_and_coverage(pop, metrics[m], lift, trials) for m, lift in POWER_CASES]
    peek = validate.peeking(pop, metrics["deposit_conversion"], n, looks=5, trials=trials)
    srm_false, srm_hit = validate.srm_rates(50_000, 20_000, drop=0.03)

    out = [
        "# Validation of the statistics",
        "",
        f"Generated by `gamma validate` on {datetime.now(UTC):%Y-%m-%d}, {trials} trials per row,"
        f" in {time.time() - started:.0f} s.",
        "",
        f"The population is the {players:,} players of `{NULL_EXPERIMENT}`, an experiment with no real "
        "effect, so the arms are interchangeable and any difference is noise. The estimators are the "
        "production ones (`gamma.analyze.estimate_metric`); the data is the heavy-tailed "
        "output of the platform's own pipeline, not a textbook normal. A rate near the nominal "
        "level, within its own margin (the `±`, a 95% interval for the rate), means the method "
        "keeps its promise.",
        "",
        "## 1. A/A: how often a method finds an effect that is not there",
        "",
        f"Random 50/50 splits with {n:,} players per arm. Nominal: 5%.",
        "",
        "| Metric | Method | False positive rate |",
        "| --- | --- | --- |",
    ]
    for metric, methods in fpr.items():
        for method, rate in methods.items():
            out.append(f"| `{metric}` | {method} | {rate} |")
    out += [
        "",
        "## 2. Power, interval coverage and what CUPED buys",
        "",
        "A known relative lift is planted in the treatment arm and the test is run at the sample size"
        " the design formula (`gamma.stats.design`) prescribes for 80% power. *Coverage* is how often"
        " the 95% interval of the deciding method contains the planted lift (nominal 95%).",
        "",
        "| Metric | Planted lift | Players per arm | Power, raw | Power, CUPED | Coverage | Variance with CUPED / without |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in power:
        cuped = str(r.cuped) if r.cuped else "n/a"
        ratio = f"{r.variance_ratio:.2f}" if r.variance_ratio is not None else "n/a"
        out.append(
            f"| `{r.metric}` | {r.lift:+.0%} | {r.n:,} | {r.raw} | {cuped} | {r.coverage} | {ratio} |"
        )
    out += [
        "",
        "## 3. Peeking",
        "",
        f"A/A tests looked at {peek.looks} times, at equal steps of the sample, on `deposit_conversion`."
        ' "Naive" stops at the first look with p < 0.05. "Sequential" uses O\'Brien-Fleming boundaries'
        ' planned for the same looks. "Fixed" looks once, at the end.',
        "",
        "| Procedure | False positive rate (nominal 5%) |",
        "| --- | --- |",
        f"| Naive peeking | {peek.naive} |",
        f"| Sequential, O'Brien-Fleming | {peek.sequential} |",
        f"| Fixed horizon | {peek.fixed} |",
        "",
        "Critical z-values of the O'Brien-Fleming plan (two-sided, alpha 0.05):",
        "",
        "| Looks | z at each look |",
        "| --- | --- |",
    ]
    for k in (2, 3, 5):
        zs = sequential.boundaries([(i + 1) / k for i in range(k)])
        out.append(f"| {k} | " + ", ".join(f"{z:.2f}" for z in zs) + " |")
    out += [
        "",
        "## 4. Sample ratio mismatch",
        "",
        "50,000 players per arm, 20,000 trials, threshold p < 0.001.",
        "",
        "| Situation | Check fires |",
        "| --- | --- |",
        f"| Honest 50/50 split | {srm_false} |",
        f"| 3% of the treatment arm silently missing | {srm_hit} |",
        "",
        "## How to read this",
        "",
        "- Every trial re-splits the same finite pool of players, so rows are not independent"
        " experiments; the `±` shows the Monte Carlo error of each rate, not more.",
        "- A point or so off nominal on the money metrics at 10,000 players per arm is the normal"
        " approximation straining on a skewed metric. The percentile bootstrap printed by"
        " `gamma analyze` is the cross-check for those.",
        "- For the same reason power on a heavy-tailed continuous metric can land a few points under the"
        " planned 80% (`deposit_per_player` does). Plan with margin there.",
        "- Interval coverage of a *relative* lift uses the delta method, which is approximate; it is"
        " expected to sit slightly under 95% at small effects.",
        "",
    ]
    return "\n".join(out)
